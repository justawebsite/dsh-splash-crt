/**
 * 构建：把 src/client/index.js（单文件 ESM，零运行时依赖）打成 IIFE
 * 输出到 lib/client.js，由宿主半区经 /dsh-splash/client.js 下发。
 *
 * 之所以自己打包而不是走 `dsh.client` 客户端模块注册表：开屏需要一块盖住
 * 整页、抢在首帧之前隐藏界面、并且完全接管指针事件的自挂载浮层；那条通道
 * 是给 React 槽位组件用的。打包只为把源码收成一个可直接 <script> 的文件。
 */
import { build } from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'lib', 'client.js')
fs.mkdirSync(path.dirname(outfile), { recursive: true })

const result = await build({
  entryPoints: [path.join(root, 'src', 'client', 'index.js')],
  outfile,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome120'],
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: { js: '/* dsh-splash-crt · browser half · generated by tools/build.mjs */' },
  logLevel: 'info',
  metafile: true,
})

const bytes = fs.statSync(outfile).size
console.log(`[build] lib/client.js  ${(bytes / 1024).toFixed(1)} KiB`)
const outputs = result.metafile.outputs
for (const [file, info] of Object.entries(outputs)) {
  if (info.bytes > 200000) {
    for (const [dep, d] of Object.entries(info.inputs)) {
      if (d.bytesInOutput > 20000) console.log(`        ${dep}  ${(d.bytesInOutput / 1024).toFixed(1)} KiB`)
    }
  }
}
